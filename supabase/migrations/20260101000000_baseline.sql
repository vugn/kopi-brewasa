-- Name: process_transaction_stock(uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.process_transaction_stock(transaction_uuid uuid) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    AS $$
declare
    t_item record;
    recipe_item record;
    needed_qty numeric;
begin
    for t_item in 
        select * from public.transaction_items where transaction_id = transaction_uuid
    loop
        for recipe_item in 
            select * from public.menu_recipes where menu_item_id = t_item.menu_item_id
        loop
            needed_qty := recipe_item.quantity_required * t_item.quantity;
            update public.ingredients
            set current_stock = current_stock - needed_qty
            where id = recipe_item.ingredient_id;

            insert into public.stock_logs (ingredient_id, change_amount, reason, notes)
            values (recipe_item.ingredient_id, -needed_qty, 'sale', 'Sold via POS: ' || t_item.item_name);
        end loop;
    end loop;
end;
$$;


